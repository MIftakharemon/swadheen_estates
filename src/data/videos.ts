export function getVideos(kind?: VideoKind, projectSlug?: string): ProjectVideo[] {
  return projectVideos
    .filter(
      (video) =>
        (!kind || video.kind === kind) &&
        (!projectSlug || video.projectSlug === projectSlug) &&
        video.published,
    )
    .sort((a, b) => a.sortOrder - b.sortOrder)
}

export function youtubeEmbedUrl(video: Pick<ProjectVideo, 'youtubeId'>): string {
  return `https://www.youtube-nocookie.com/embed/${video.youtubeId}?rel=0&modestbranding=1&playsinline=1`
}
